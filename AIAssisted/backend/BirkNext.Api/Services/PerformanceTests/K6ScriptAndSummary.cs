using Path = System.IO.Path;
using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using BirkNext.PerformanceTests;

namespace BirkNext.Api.Services.PerformanceTests;

/// <summary>
/// Deterministic k6 script from a validated definition. Every user-supplied value (origin, paths, headers, bodies, test data, step names) enters
/// the script only as a JSON literal produced by System.Text.Json (which escapes quotes, backslashes, &lt;, &gt;, &amp;, U+2028/2029), so it cannot
/// escape a string or inject code. The same definition always yields the same script text.
/// </summary>
public static class K6ScriptGenerator
{
    private static readonly JsonSerializerOptions Json = new() { WriteIndented = false };

    public static string Generate(PerformanceTestDefinition d, PerformanceTestDataProfile? data, string summaryPath)
    {
        // Steps run in their saved order (the list order) — never re-sorted by id or name.
        var steps = d.Scenario.Steps.Where(s => !s.Disabled).Select(s => new JsonObject
        {
            ["id"] = s.Id, ["name"] = s.Name, ["method"] = s.Method.ToUpperInvariant(), ["path"] = s.RelativePath,
            ["query"] = new JsonArray(s.QueryParameters.Select(q => (JsonNode)new JsonArray(q.Name, q.Value)).ToArray()),
            ["headers"] = new JsonObject(Headers(d, s).Select(h => KeyValuePair.Create(h.Key, (JsonNode?)h.Value))),
            ["body"] = Body(d, s), ["expected"] = new JsonArray(s.ExpectedStatusCodes.Distinct().Order().Select(c => (JsonNode)c).ToArray()),
            ["thinkMs"] = s.ThinkTimeMs ?? 0,
            ["bind"] = Bindings(d, s), ["bodyMode"] = PerformanceRequestResponse.BodyEncoding(s, d.TargetType == PerformanceTargetType.GraphQlHttp),
            // [name, selector] reads the JSON body (k6 Response.json selector); [name, header, "header"] reads a response header.
            ["outputs"] = new JsonArray((s.Outputs ?? []).Where(o => PerformanceRequestResponse.OutputProblem(o) is null)
                .Select(o => (JsonNode)(o.From == StepOutputSource.Header ? new JsonArray(o.Name, o.Path, "header") : new JsonArray(o.Name, PerformanceScenarioRuntime.Selector(o.Path)))).ToArray()),
        }).ToList();
        var columns = data?.Columns ?? [];
        var rows = data?.Rows.Select(r => columns.Select((c, i) => (c, v: i < r.Count ? r[i] : "")).ToDictionary(x => x.c, x => x.v)).ToList() ?? [];
        var sb = new StringBuilder();
        sb.Append("// Generated by BirkNext from performance test definition ").Append(Lit(d.Id)).Append(" v").Append(d.Version).Append(". Do not edit.\n");
        sb.Append("import http from 'k6/http';\nimport { sleep } from 'k6';\nimport exec from 'k6/execution';\nimport { Counter } from 'k6/metrics';\n");
        sb.Append("const ORIGIN = ").Append(Lit(d.TargetOrigin.TrimEnd('/'))).Append(";\n");
        sb.Append("const STEPS = ").Append(JsonSerializer.Serialize(steps, Json)).Append(";\n");
        sb.Append("const ROWS = ").Append(JsonSerializer.Serialize(rows, Json)).Append(";\n");
        sb.Append("const SELECTION = ").Append(Lit((data?.Selection ?? TestDataSelection.RoundRobin).ToString())).Append(";\n");
        sb.Append("const SUMMARY_PATH = ").Append(Lit(summaryPath)).Append(";\n");
        sb.Append("const GRAPHQL = ").Append(d.TargetType == PerformanceTargetType.GraphQlHttp ? "true" : "false").Append(";\n");
        sb.Append("const thresholds = {};\nfor (const s of STEPS) {\n");
        sb.Append("  thresholds[`http_req_duration{name:${s.name}}`] = ['max>=0'];\n  thresholds[`http_req_failed{name:${s.name}}`] = ['rate>=0'];\n  thresholds[`http_reqs{name:${s.name}}`] = ['count>=0'];\n");
        sb.Append("  for (const m of ['birknext_unresolved_value', 'birknext_extraction_missing', 'birknext_graphql_errors']) thresholds[`${m}{name:${s.name}}`] = ['count>=0'];\n}\n");
        sb.Append("export const options = {\n  scenarios: { workload: ").Append(Scenario(d.Workload)).Append(" },\n");
        sb.Append("  thresholds,\n  summaryTrendStats: ['avg', 'min', 'med', 'max', 'p(90)', 'p(95)', 'p(99)'],\n  discardResponseBodies: true,\n};\n");
        sb.Append("""
            function row() {
              if (ROWS.length === 0) return {};
              let i;
              if (SELECTION === 'Sequential') i = exec.scenario.iterationInTest;
              else if (SELECTION === 'Random') i = Math.floor(Math.random() * ROWS.length);
              else if (SELECTION === 'UniquePerVirtualUser') i = exec.vu.idInTest - 1;
              else i = exec.vu.idInTest - 1 + exec.vu.iterationInInstance;
              return ROWS[i % ROWS.length];
            }
            function uuid() {
              return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => { const n = Math.random() * 16 | 0; return (c === 'x' ? n : (n & 0x3 | 0x8)).toString(16); });
            }
            function generated(g) {
              if (g === 'Uuid') return uuid();
              if (g === 'Timestamp') return new Date().toISOString();
              return String(Math.floor(Math.random() * 1000000000));
            }
            function value(s, k, r, ctx) {
              const b = s.bind[k];
              if (b === undefined) return Object.prototype.hasOwnProperty.call(r, k) ? r[k] : undefined;
              if (b.k === 'row') return Object.prototype.hasOwnProperty.call(r, b.c) ? r[b.c] : undefined;
              if (b.k === 'step') return ctx[`${b.s}.${b.o}`];
              if (b.k === 'fixed') return b.v;
              if (b.k === 'gen') return generated(b.g);
              return undefined;
            }
            // Each value is encoded for where it goes: path segment, header, JSON string, XML text, form field; a whole-payload body is inserted as is.
            function enc(v, mode) {
              const t = String(v);
              if (mode === 'path' || mode === 'form') return encodeURIComponent(t);
              if (mode === 'json') return JSON.stringify(t).slice(1, -1);
              if (mode === 'xml') return t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;');
              if (mode === 'header') return t.replace(/[\r\n]/g, '');
              return t;
            }
            function fill(text, s, r, ctx, mode, miss) {
              if (text === null) return null;
              return text.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g, (m, k) => {
                const v = value(s, k, r, ctx);
                if (v === undefined || v === null) { miss.push(k); return m; }
                return enc(v, mode);
              });
            }
            function header(res, name) {
              const want = name.toLowerCase();
              for (const k of Object.keys(res.headers)) if (k.toLowerCase() === want) return res.headers[k];
              return undefined;
            }
            const UNRESOLVED = new Counter('birknext_unresolved_value');
            const EXTRACTION_MISSING = new Counter('birknext_extraction_missing');
            const GRAPHQL_ERRORS = new Counter('birknext_graphql_errors');
            const STATUS = {};
            for (const code of [200, 201, 202, 204, 301, 302, 304, 400, 401, 403, 404, 409, 422, 429, 500, 502, 503, 504]) STATUS[code] = new Counter(`birknext_status_${code}`);
            const STATUS_OTHER = { 1: new Counter('birknext_status_1xx_other'), 2: new Counter('birknext_status_2xx_other'), 3: new Counter('birknext_status_3xx_other'),
              4: new Counter('birknext_status_4xx_other'), 5: new Counter('birknext_status_5xx_other') };
            const TRANSPORT = { timeout: new Counter('birknext_error_timeout'), connection: new Counter('birknext_error_connection'), tls: new Counter('birknext_error_tls'),
              other: new Counter('birknext_error_other') };
            function count(res) {
              if (res.status > 0) { (STATUS[res.status] || STATUS_OTHER[Math.floor(res.status / 100)] || STATUS_OTHER[5]).add(1); return; }
              const c = res.error_code || 0;
              if (c === 1050) TRANSPORT.timeout.add(1);
              else if (c >= 1300 && c < 1400) TRANSPORT.tls.add(1);
              else if (c >= 1100 && c < 1300) TRANSPORT.connection.add(1);
              else TRANSPORT.other.add(1);
            }
            // ctx holds the outputs of THIS iteration of THIS virtual user only: a value extracted by one VU is never seen by another, and nothing
            // carries over between iterations (no shared mutable state).
            export default function () {
              const r = row();
              const ctx = {};
              for (const s of STEPS) {
                const miss = [];
                const q = s.query.map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(fill(v, s, r, ctx, 'text', miss))}`).join('&');
                const url = ORIGIN + fill(s.path, s, r, ctx, 'path', miss) + (q.length > 0 ? `?${q}` : '');
                const headers = {};
                for (const h of Object.keys(s.headers)) headers[h] = fill(s.headers[h], s, r, ctx, 'header', miss);
                const body = fill(s.body, s, r, ctx, s.bodyMode, miss);
                // A value that did not resolve (e.g. the producing step's response lacked the output) is a counted failure: the request is not sent
                // with a literal {placeholder} and no stale or sample value is substituted.
                if (miss.length > 0) { UNRESOLVED.add(1, { name: s.name }); continue; }
                const params = { headers, tags: { name: s.name }, responseCallback: http.expectedStatuses(...s.expected) };
                if (GRAPHQL || s.outputs.some((o) => o[2] !== 'header')) params.responseType = 'text';
                const res = http.request(s.method, url, body, params);
                count(res);
                if (GRAPHQL) {
                  // HTTP 200 with GraphQL errors is a GraphQL failure, counted apart from the HTTP status.
                  let errors;
                  try { errors = res.json('errors'); } catch (e) { errors = undefined; }
                  if (Array.isArray(errors) && errors.length > 0) GRAPHQL_ERRORS.add(1, { name: s.name });
                }
                for (const [name, selector, from] of s.outputs) {
                  let v;
                  if (from === 'header') v = header(res, selector);
                  else { try { v = res.json(selector); } catch (e) { v = undefined; } }
                  // An array or object is not one value: never silently the first element.
                  if (v !== undefined && v !== null && typeof v === 'object') v = undefined;
                  if (v === undefined || v === null) EXTRACTION_MISSING.add(1, { name: s.name });
                  ctx[`${s.id}.${name}`] = v;
                }
                if (s.thinkMs > 0) sleep(s.thinkMs / 1000);
              }
            }
            export function handleSummary(data) {
              const out = {};
              out[SUMMARY_PATH] = JSON.stringify({ birknext: 1, metrics: data.metrics, state: data.state });
              return out;
            }

            """);
        return sb.ToString();
    }

    /// <summary>One GET of the origin (1 VU, 1 iteration, 15 s timeout) recording the HTTP status and k6 error code — the container-network check.</summary>
    public static string Probe(string origin, string resultPath) =>
        "// Generated by BirkNext: container-network reachability check (one request). Do not edit.\n"
        + "import http from 'k6/http';\nimport { Trend } from 'k6/metrics';\n"
        + "const ORIGIN = " + Lit(origin.TrimEnd('/')) + ";\nconst OUT = " + Lit(resultPath) + ";\n"
        + "const status = new Trend('birknext_probe_status');\nconst code = new Trend('birknext_probe_error');\n"
        + "export const options = { vus: 1, iterations: 1, summaryTrendStats: ['max'] };\n"
        + "export default function () { const r = http.get(ORIGIN + '/', { timeout: '15s' }); status.add(r.status); code.add(r.error_code || 0); }\n"
        + "export function handleSummary(data) { const o = {}; o[OUT] = JSON.stringify({ birknext: 1, metrics: data.metrics }); return o; }\n";

    private static string Lit(string value) => JsonSerializer.Serialize(value, Json);

    /// <summary>
    /// How each placeholder of a step gets its value: a Test Data column, an earlier step's output (read from the response at run time), a fixed
    /// value, a scenario variable or a generated value. Unmapped placeholders fall back to a legacy profile column of the same name.
    /// </summary>
    private static JsonObject Bindings(PerformanceTestDefinition d, HttpPerformanceStep s)
    {
        var bind = new JsonObject();
        foreach (var m in s.DataMappings ?? [])
        {
            JsonObject? node = m.Source switch
            {
                RuntimeValueSource.TestData => new JsonObject { ["k"] = "row", ["c"] = m.Variable },
                RuntimeValueSource.PreviousStep when m.FromStepId is not null && m.Output is not null => new JsonObject { ["k"] = "step", ["s"] = m.FromStepId, ["o"] = m.Output },
                RuntimeValueSource.Fixed or RuntimeValueSource.AutoFilled when m.FixedValue is not null => new JsonObject { ["k"] = "fixed", ["v"] = m.FixedValue },
                RuntimeValueSource.Generated when m.Generator is { } g => new JsonObject { ["k"] = "gen", ["g"] = g.ToString() },
                RuntimeValueSource.ScenarioVariable => d.Scenario.Variables?.FirstOrDefault(v => v.Name == m.ScenarioVariable) switch
                {
                    { Source: RuntimeValueSource.Fixed, Value: { } v } => new JsonObject { ["k"] = "fixed", ["v"] = v },
                    { Source: RuntimeValueSource.Generated, Generator: { } g } => new JsonObject { ["k"] = "gen", ["g"] = g.ToString() },
                    { Source: RuntimeValueSource.TestData } v => new JsonObject { ["k"] = "row", ["c"] = PerformanceCentralTestData.VariableColumn(v.Name) },
                    _ => null,
                },
                _ => null,
            };
            if (node is not null) bind[m.Variable] = node;
        }
        return bind;
    }

    private static IEnumerable<KeyValuePair<string, string>> Headers(PerformanceTestDefinition d, HttpPerformanceStep s)
    {
        var headers = s.Headers.Select(h => KeyValuePair.Create(h.Name, h.Value)).ToList();
        var contentType = d.TargetType == PerformanceTargetType.GraphQlHttp ? "application/json" : s.ContentType;
        if (contentType is not null && !headers.Any(h => h.Key.Equals("Content-Type", StringComparison.OrdinalIgnoreCase))) headers.Add(KeyValuePair.Create("Content-Type", contentType));
        return headers.OrderBy(h => h.Key, StringComparer.Ordinal);
    }

    private static string? Body(PerformanceTestDefinition d, HttpPerformanceStep s)
    {
        if (d.TargetType != PerformanceTargetType.GraphQlHttp) return s.BodyTemplate;
        var body = new JsonObject { ["query"] = s.GraphQlQuery ?? "" };
        if (!string.IsNullOrWhiteSpace(s.GraphQlOperationName)) body["operationName"] = s.GraphQlOperationName;
        if (!string.IsNullOrWhiteSpace(s.GraphQlVariablesJson)) body["variables"] = JsonNode.Parse(s.GraphQlVariablesJson);
        return body.ToJsonString(Json);
    }

    /// <summary>Generic workload → a k6 scenario. Virtual users → ramping-vus; arrival rate → ramping-arrival-rate per minute (integer rates).</summary>
    internal static string Scenario(PerformanceWorkload w)
    {
        string Stage(int seconds, double target) => $"{{ duration: '{seconds}s', target: {target.ToString(CultureInfo.InvariantCulture)} }}";
        var stages = new List<string>();
        if (w.Mode == WorkloadMode.VirtualUsers)
        {
            var vus = w.VirtualUsers ?? 1;
            var warm = PerformanceTestRules.WarmupVirtualUsers(w);
            if (w.WarmupSeconds > 0) stages.Add(Stage(w.WarmupSeconds, warm));
            if (w.RampUpSeconds > 0) stages.Add(Stage(w.RampUpSeconds, vus));
            if (w.SteadyStateSeconds > 0) stages.Add(Stage(w.SteadyStateSeconds, vus));
            if (w.RampDownSeconds > 0) stages.Add(Stage(w.RampDownSeconds, 0));
            return $"{{ executor: 'ramping-vus', startVUs: {(w.WarmupSeconds > 0 ? warm : 0)}, stages: [{string.Join(", ", stages)}], gracefulRampDown: '10s', gracefulStop: '10s' }}";
        }
        var target = (int)Math.Round((w.RequestsPerSecond ?? 1) * 60);
        var start = (int)Math.Round((w.StartRequestsPerSecond ?? Math.Max(1, (w.RequestsPerSecond ?? 1) / 10)) * 60);
        if (w.WarmupSeconds > 0) stages.Add(Stage(w.WarmupSeconds, start));
        if (w.RampUpSeconds > 0) stages.Add(Stage(w.RampUpSeconds, target));
        if (w.SteadyStateSeconds > 0) stages.Add(Stage(w.SteadyStateSeconds, target));
        if (w.RampDownSeconds > 0) stages.Add(Stage(w.RampDownSeconds, 0));
        var maxVus = Math.Max(1, w.VirtualUsers ?? 10);
        var pre = Math.Min(maxVus, Math.Max(1, (int)Math.Ceiling(w.RequestsPerSecond ?? 1)));
        return $"{{ executor: 'ramping-arrival-rate', startRate: {start}, timeUnit: '1m', preAllocatedVUs: {pre}, maxVUs: {maxVus}, stages: [{string.Join(", ", stages)}], gracefulStop: '10s' }}";
    }
}

/// <summary>Normalizes the k6 end-of-test summary into provider-independent metrics. Missing or malformed output is an error, never zero metrics.</summary>
public static class K6SummaryParser
{
    public static (PerformanceMetrics? Metrics, string? Error) Parse(string json, IReadOnlyList<string> stepNames)
    {
        JsonNode? root;
        try { root = JsonNode.Parse(json); }
        catch (JsonException) { return (null, "The k6 summary is not valid JSON."); }
        if (root?["metrics"] is not JsonObject metrics) return (null, "The k6 summary has no metrics section.");
        var reqs = Values(metrics, "http_reqs");
        var duration = Values(metrics, "http_req_duration");
        if (reqs is null || duration is null) return (null, "The k6 summary has no HTTP request metrics (no request was issued or the summary is incomplete).");
        var count = Long(reqs, "count") ?? 0;
        var failedValues = Values(metrics, "http_req_failed");
        // http_req_failed is a Rate: "passes" counts failed requests (value true), "fails" counts successful ones.
        long? failed = Long(failedValues, "passes");
        long? ok = Long(failedValues, "fails");
        var steps = stepNames.Distinct().Select(name =>
        {
            var d = Values(metrics, $"http_req_duration{{name:{name}}}");
            var f = Values(metrics, $"http_req_failed{{name:{name}}}");
            var r = Values(metrics, $"http_reqs{{name:{name}}}");
            return d is null || r is null ? null : new PerformanceStepMetrics(name, Long(r, "count") ?? 0, Double(f, "rate") is { } rate ? Math.Round(rate * 100, 3) : null,
                Double(d, "p(95)"), Double(d, "p(99)"), Double(r, "rate"))
            {
                Unresolved = Positive(metrics, $"birknext_unresolved_value{{name:{name}}}"), ExtractionMissing = Positive(metrics, $"birknext_extraction_missing{{name:{name}}}"),
                GraphQlErrors = Positive(metrics, $"birknext_graphql_errors{{name:{name}}}"),
            };
        }).Where(s => s is not null).Cast<PerformanceStepMetrics>().ToList();
        var stateMs = root["state"]?["testRunDurationMs"]?.GetValue<double>();
        return (new PerformanceMetrics
        {
            RequestCount = count, FailedRequests = failed ?? 0, SuccessfulRequests = ok ?? Math.Max(0, count - (failed ?? 0)),
            ErrorRatePercent = Double(failedValues, "rate") is { } er ? Math.Round(er * 100, 3) : null,
            RequestsPerSecond = Double(reqs, "rate") is { } rps ? Math.Round(rps, 3) : null,
            DurationSeconds = stateMs is { } ms ? Math.Round(ms / 1000, 1) : 0,
            Latency = new PerformanceLatency
            {
                MinMs = Double(duration, "min"), MeanMs = Double(duration, "avg"), P50Ms = Double(duration, "med"), P90Ms = Double(duration, "p(90)"),
                P95Ms = Double(duration, "p(95)"), P99Ms = Double(duration, "p(99)"), MaxMs = Double(duration, "max"),
            },
            Steps = steps,
            DroppedIterations = Long(Values(metrics, "dropped_iterations"), "count"),
            StatusCodes = Counted(metrics, "birknext_status_", name => name.EndsWith("_other", StringComparison.Ordinal) ? $"{name[..3]} other" : name),
            TransportErrors = Counted(metrics, "birknext_error_", name => name),
            Unresolved = Positive(metrics, "birknext_unresolved_value"), ExtractionMissing = Positive(metrics, "birknext_extraction_missing"),
            GraphQlErrors = Positive(metrics, "birknext_graphql_errors"),
        }, null);
    }

    /// <summary>A counter's count when it received samples (null otherwise, so older runs and clean runs serialize unchanged).</summary>
    private static long? Positive(JsonObject metrics, string key) => Long(Values(metrics, key), "count") is > 0 and var n ? n : null;

    /// <summary>
    /// Counter metrics with a prefix (k6 reports only counters that received samples). Null when the script did not count at all — an older
    /// script, so "not captured" rather than zero; a script that counts always reports at least one status or transport failure.
    /// </summary>
    private static Dictionary<string, long>? Counted(JsonObject metrics, string prefix, Func<string, string> label)
    {
        var captured = metrics.Any(m => m.Key.StartsWith("birknext_status_", StringComparison.Ordinal) || m.Key.StartsWith("birknext_error_", StringComparison.Ordinal));
        if (!captured) return null;
        return metrics.Where(m => m.Key.StartsWith(prefix, StringComparison.Ordinal) && !m.Key.Contains('{'))
            .Select(m => (Key: label(m.Key[prefix.Length..]), Count: Long(Values(metrics, m.Key), "count") ?? 0)).Where(x => x.Count > 0)
            .OrderBy(x => x.Key, StringComparer.Ordinal).ToDictionary(x => x.Key, x => x.Count);
    }

    /// <summary>The probe's HTTP status (0 = no response) and k6 error code, or nulls when the result is unreadable.</summary>
    public static (int? Status, int? ErrorCode) Probe(string json)
    {
        try
        {
            if (JsonNode.Parse(json)?["metrics"] is not JsonObject metrics) return (null, null);
            return ((int?)Double(Values(metrics, "birknext_probe_status"), "max"), (int?)Double(Values(metrics, "birknext_probe_error"), "max"));
        }
        catch (JsonException) { return (null, null); }
    }

    private static JsonObject? Values(JsonObject metrics, string key) => metrics[key]?["values"] as JsonObject;

    private static double? Double(JsonObject? values, string key) =>
        values?[key] is JsonValue v && v.TryGetValue<double>(out var d) && double.IsFinite(d) ? Math.Round(d, 3) : null;

    private static long? Long(JsonObject? values, string key) => Double(values, key) is { } d ? (long)Math.Round(d) : null;
}
