using System.Text.RegularExpressions;
using BirkNext.TestCoverage;

namespace BirkNext.Api.Services.TestPlanning;

/// <summary>
/// Turns one specification acceptance scenario (Given / When / Then) into a manual test-case draft that a tester can work from, without inventing
/// anything the source does not say (2026-11-24). Deterministic, generic rules — no service-specific parser:
/// <list type="bullet">
/// <item>Given → preconditions and the test-data requirement, kept verbatim (values, inequalities, roles stay exact).</item>
/// <item>When → one action. A leading pronoun is resolved from the Given ("it" → its object, "they" → its actor). The action is classified:
/// something <b>arrives</b> (an incoming report, change, message — sent by the actor the user story names, if any), the <b>system processes</b>
/// something (mapped, translated, executes …), or a <b>person acts</b> (searches, types, presses …). How an arrival is sent or a processing is
/// triggered is never invented: it is listed as unresolved.</item>
/// <item>Then → verification points, split only at clause boundaries (", and", ";") so a list such as "stored, published or logged" is never
/// broken; negative assertions are kept and get a note that where they can be checked is unresolved. A "; where …" clause is a separate variant.</item>
/// </list>
/// Used for new drafts only; saved cases are never regenerated by it.
/// </summary>
public static partial class AcceptanceScenarioInterpreter
{
    public enum ActionKind { PersonActs, Arrival, SystemProcessing, AsWritten }

    public sealed record Interpretation(
        string? Preconditions,
        string? TestDataRequirement,
        string Action,
        ActionKind Kind,
        IReadOnlyList<string> Expected,
        IReadOnlyList<string> Unresolved,
        IReadOnlyList<string> Variants);

    [GeneratedRegex(@"^(?:a|an|the|some|another)\s+", RegexOptions.IgnoreCase)]
    private static partial Regex Article();

    [GeneratedRegex(@"\b(case ?worker|saksbehandler|administrator|admin|user|developer|reporter|tester|operator|clerk|employee|teacher|guardian|reviewer|auditor|manager)s?\b", RegexOptions.IgnoreCase)]
    private static partial Regex Role();

    [GeneratedRegex(@"^(it|they|this|that)\b\s*", RegexOptions.IgnoreCase)]
    private static partial Regex LeadingPronoun();

    [GeneratedRegex(@"\b(arrives?|arriving|is received|are received|comes in|come in|is delivered|are delivered|is submitted|are submitted)\b", RegexOptions.IgnoreCase)]
    private static partial Regex ArrivalVerb();

    [GeneratedRegex(@"^(?:.+?\s)?(is|are|gets|get)\s+(\w+ed|\w+en|run|set|sent|written|read|built|made)\b|\b(executes|completes|runs|processes|attempts|maps|translates|applies|acknowledges)\b", RegexOptions.IgnoreCase)]
    private static partial Regex SystemVerb();

    [GeneratedRegex(@"(?<actor>\b(?:a|an|the)\s[^.;:\[\]]*?)\s(?<verb>submits|sends|delivers|reports|posts|publishes|uploads)\b", RegexOptions.IgnoreCase)]
    private static partial Regex StoryActor();

    [GeneratedRegex(@"\b(not|no|never|without|none|nothing)\b", RegexOptions.IgnoreCase)]
    private static partial Regex Negation();

    private static readonly string[] Boundary =
        ["for", "with", "where", "whose", "who", "that", "which", "without", "in", "of", "on", "at", "from", "to", "listing", "containing", "and", "or", "is", "are", "has", "have", "whose"];

    /// <summary>The head of the Given's leading noun phrase ("a report for a child …" → "report"; "the same message delivered twice" → "same message").</summary>
    public static string? SubjectOf(string? given)
    {
        if (string.IsNullOrWhiteSpace(given)) return null;
        var words = Article().Replace(given.Trim(), "").Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
        var head = new List<string>();
        foreach (var raw in words)
        {
            var w = raw.Trim(',', ';', '.', ':', '`', '"', '\'');
            if (head.Count > 0 && (Boundary.Contains(w, StringComparer.OrdinalIgnoreCase) || w.EndsWith("ed", StringComparison.Ordinal) && w.Length > 4)) break;
            if (w.Length == 0) break;
            head.Add(w);
            if (raw.EndsWith(',') || head.Count == 4) break;
        }
        return head.Count == 0 ? null : string.Join(' ', head);
    }

    /// <summary>The person in the Given ("Given a caseworker without classification access" → "caseworker"); null when none is named.</summary>
    public static string? ActorOf(string? given) => given is null ? null : Role().Match(given) is { Success: true } m ? m.Value.ToLowerInvariant() : null;

    /// <summary>Who sends things according to the user story ("A private institution or a foster home submits …").</summary>
    public static string? SenderOf(CoverageUserStory? story) =>
        story?.Description is { Length: > 0 } d && StoryActor().Match(d) is { Success: true } m ? m.Groups["actor"].Value.Trim() : null;

    public static Interpretation Interpret(string? given, string when, string? then, CoverageUserStory? story)
    {
        var unresolved = new List<string>();
        var subject = SubjectOf(given);
        var actor = ActorOf(given);
        var trimmed = when.Trim().TrimEnd('.', ',');
        var pronoun = LeadingPronoun().Match(trimmed);
        var rest = pronoun.Success ? trimmed[pronoun.Length..] : trimmed;
        var pronounWord = pronoun.Success ? pronoun.Groups[1].Value.ToLowerInvariant() : null;

        string action;
        ActionKind kind;
        if (ArrivalVerb().IsMatch(trimmed))
        {
            kind = ActionKind.Arrival;
            var what = pronounWord is "it" or "this" or "that" ? subject : ArrivingThing(trimmed) ?? subject;
            var sender = SenderOf(story);
            action = what is null ? Capital(trimmed) + "."
                : sender is not null ? $"Send the {what} in as {Lower(sender)}."
                : $"Make the {what} arrive{(string.IsNullOrWhiteSpace(given) || pronounWord is not null ? "" : $" ({Lower(given.Trim().TrimEnd('.', ','))})")}.";
            unresolved.Add(what is null
                ? "What arrives is not stated in the scenario — clarify what is sent."
                : $"How the {what} is sent in the test environment is not stated in the source — clarify before execution.");
        }
        else if (pronounWord == "they" || StartsWithRole(trimmed))
        {
            kind = ActionKind.PersonActs;
            if (pronounWord == "they")
            {
                if (actor is null)
                {
                    action = $"{Capital(rest)}.";
                    unresolved.Add("Who acts (\"they\") is not stated in the scenario — clarify the role.");
                }
                else action = $"As the {actor}: {rest}.";
            }
            else action = Capital(trimmed) + ".";
        }
        else if (pronounWord is "it" or "this" or "that" && SystemVerb().IsMatch(rest) || SystemVerb().IsMatch(trimmed))
        {
            kind = ActionKind.SystemProcessing;
            var resolved = pronounWord is "it" or "this" or "that" && subject is not null ? $"the {subject} {rest}" : ResolveTrailingIt(trimmed, subject);
            // 2026-11-26: no vague «Trigger and observe»; the event as the source states it, and the missing action said plainly (never invented).
            action = $"{Capital(resolved)} (the action that makes this happen in the test environment must be specified).";
            unresolved.Add("How this processing is triggered and observed in the test environment is not stated in the source — clarify before execution.");
        }
        else
        {
            kind = ActionKind.AsWritten;
            action = pronounWord is "it" or "this" or "that" && subject is not null ? $"The {subject} {rest}." : Capital(trimmed) + ".";
            if (pronounWord is not null && subject is null) unresolved.Add($"What \"{pronounWord}\" refers to is not stated in the scenario — clarify.");
            // An event without a person ("the period locks"): what makes it happen in a test environment is not in the source.
            else unresolved.Add("How this is brought about in the test environment is not stated in the source — clarify before execution.");
        }

        var (expected, variants) = Assertions(then, subject, actor);
        foreach (var assertion in expected.Where(a => Negation().IsMatch(a)))
            unresolved.Add($"Where it can be verified that {Lower(assertion.TrimEnd('.'))} is not stated in the source — clarify access before execution.");
        // The Given and the Then stay verbatim (source text); only the composed action is a sentence of its own.
        var verbatimGiven = string.IsNullOrWhiteSpace(given) ? null : given.Trim().TrimEnd(',');
        return new Interpretation(verbatimGiven, verbatimGiven, action, kind, expected, unresolved, variants);
    }

    /// <summary>The Then clause as verification points (clause boundaries only) and any "; where …" variants.</summary>
    public static (IReadOnlyList<string> Expected, IReadOnlyList<string> Variants) Assertions(string? then, string? subject, string? actor = null)
    {
        if (string.IsNullOrWhiteSpace(then)) return ([], []);
        var expected = new List<string>();
        var variants = new List<string>();
        foreach (var part in then.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            if (Regex.IsMatch(part, @"^(where|when|if|unless|otherwise)\b", RegexOptions.IgnoreCase) && expected.Count > 0)
            {
                variants.Add(part);
                continue;
            }
            foreach (var clause in Regex.Split(part, @",\s+and\s+", RegexOptions.IgnoreCase))
            {
                var text = clause.Trim().TrimEnd(',');
                if (text.Length == 0) continue;
                var pronoun = LeadingPronoun().Match(text);
                var word = pronoun.Success ? pronoun.Groups[1].Value.ToLowerInvariant() : null;
                if (word is "it" or "this" or "that" && subject is not null) text = $"the {subject} {text[pronoun.Length..]}";
                else if (word == "they" && actor is not null) text = $"the {actor} {text[pronoun.Length..]}";
                expected.Add(text);
            }
        }
        return (expected, variants);
    }

    /// <summary>The thing named before an arrival verb ("the change arrives" → "change"; "the second copy arrives" → "second copy").</summary>
    private static string? ArrivingThing(string when)
    {
        var at = ArrivalVerb().Match(when);
        if (!at.Success || at.Index == 0) return null;
        var before = Article().Replace(when[..at.Index].Trim(), "");
        return LeadingPronoun().IsMatch(before) || before.Length == 0 ? null : before;
    }

    /// <summary>A role at the start of the clause ("a case worker queries …", "the administrator opens …").</summary>
    private static bool StartsWithRole(string clause) =>
        Role().Match(Article().Replace(clause, "")) is { Success: true, Index: 0 };

    /// <summary>"the intake processes it" → "the intake processes the valid message" when the Given names the object.</summary>
    private static string ResolveTrailingIt(string clause, string? subject) =>
        subject is null ? clause : Regex.Replace(clause, @"\bit$", "the " + subject, RegexOptions.IgnoreCase);

    private static string Capital(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s[1..];
    private static string Lower(string s) => s.Length == 0 ? s : char.ToLowerInvariant(s[0]) + s[1..];
}
