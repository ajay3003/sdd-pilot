    /// <summary>The stored revision with current review decisions and its linked runs (outcome from actual Execution Evidence, never inferred).</summary>
    private async Task<IntegrationSuite> ReadAsync(IntegrationSuiteRecord row, CancellationToken ct)
    {
        var suite = JsonSerializer.Deserialize<IntegrationSuite>(row.DefinitionJson, Json)!;
        var decisions = await DecisionsAsync(row.SuiteKey, ct);
        var review = suite.Review.Select(r => decisions.TryGetValue(r.Key, out var d) ? r with { Decision = d.Decision, DecidedBy = d.By, DecidedAt = d.At } : r).ToList();
        var links = await db.IntegrationSuiteRuns.AsNoTracking().Where(r => r.SuiteKey == row.SuiteKey).OrderByDescending(r => r.StartedAt).ToListAsync(ct);
        var runs = new List<SuiteRunLink>();
        var callStates = new List<(ExecutionState State, int Assertions)>();
        foreach (var link in links)
        {
            var detail = await evidence.GetAsync(link.RunId, new ExecutionCallQuery(0, 500), ct);
            var calls = detail?.Calls ?? [];
            callStates.AddRange(calls.Select(c => (c.State, c.Assertions.Count)));
            runs.Add(new SuiteRunLink(link.RunId, link.Kind, link.StartedAt, link.Initiator, detail is null ? "Evidence not found" : calls.Count == 0 ? "No calls recorded" :
                string.Join(", ", calls.GroupBy(c => c.State).OrderBy(g => g.Key).Select(g => $"{g.Count()} {g.Key.ToString().ToLowerInvariant()}")) + $" of {calls.Count}",
                JsonSerializer.Deserialize<List<Guid>>(link.TestIdsJson, Json) ?? []));
        }
        // Calls still planned, queued or running have no result yet: they never count as executed.
        callStates.RemoveAll(c => c.State is ExecutionState.Planned or ExecutionState.Queued or ExecutionState.Running);
        var outcome = callStates.Count == 0 ? SuiteExecutionOutcome.NotExecuted
            : callStates.Any(c => c.State is ExecutionState.Failed or ExecutionState.Error) ? SuiteExecutionOutcome.Failed
            // VERIFIED only when every stage is fully covered and every executed call passed with an assertion; a partial chain is at most partial.
            : suite.Stages.Count > 0 && suite.Stages.All(s => s.Coverage == SuiteStageCoverage.ExecutableAndObservable) && callStates.All(c => c.State == ExecutionState.Passed && c.Assertions > 0)
              && suite.Stages.All(s => s.ContractTests.Count > 0 && links.Any(l => (JsonSerializer.Deserialize<List<Guid>>(l.TestIdsJson, Json) ?? []).Select(g => g.ToString("D")).Intersect(s.ContractTests).Any()))
                ? SuiteExecutionOutcome.Verified
            : callStates.Any(c => c.State == ExecutionState.Passed && c.Assertions > 0) ? SuiteExecutionOutcome.PartiallyVerified
            : SuiteExecutionOutcome.Executed;
        // Decisions recorded after generation are overlaid here, so the review dimension and the status follow them without a new revision.
        var open = review.Count(r => r.Decision is null);
        var readiness = suite.Readiness.Select(d => d.Name == "Review"
            ? d with { State = open == 0 ? SuiteItemReadiness.Ready : SuiteItemReadiness.NeedsReview, Detail = $"{open} open review item(s)" } : d).ToList();
        var (status, reason) = IntegrationSuiteComposer.Status(readiness, review, suite.Stages);
        if (suite.Composite is not null)
        {
            // Composite suites: the verdict comes only from composite runs (one continuous transaction each); flat test runs never verify E2E.
            var (composite, compositeRuns) = await CompositeOverlayAsync(suite with { Review = review }, ct);
            outcome = compositeRuns.Any(r => r.Verdict == CompositeRunVerdict.FullE2EVerified) ? SuiteExecutionOutcome.Verified
                : compositeRuns.Any(r => r.Verdict == CompositeRunVerdict.SubflowVerified) ? SuiteExecutionOutcome.PartiallyVerified
                : compositeRuns.FirstOrDefault() is { Verdict: CompositeRunVerdict.Failed or CompositeRunVerdict.WrongCorrelation } ? SuiteExecutionOutcome.Failed
                : compositeRuns.Count > 0 ? SuiteExecutionOutcome.Executed : SuiteExecutionOutcome.NotExecuted;
            (status, reason) = CompositeStatus(composite, status, reason);
            return suite with { Review = review, Runs = runs, Outcome = outcome, Readiness = readiness, Status = status, StatusReason = reason, Composite = composite };
        }
        return suite with { Review = review, Runs = runs, Outcome = outcome, Readiness = readiness, Status = status, StatusReason = reason };
    }

    private async Task<Dictionary<string, (string Decision, string By, DateTimeOffset At)>> DecisionsAsync(string suiteKey, CancellationToken ct) =>
        (await reviews.ListAsync(ManualReviewModules.IntegrationSuites, suiteKey, ct: ct)).Where(r => r.Current)
            .ToDictionary(r => r.SubjectKey, r => (r.Decision.ToString(), r.Reviewer, r.DecidedAt), StringComparer.Ordinal);

    public async Task<(ManualReviewDecisionView? Decision, string? Error)> ReviewAsync(Guid id, IntegrationSuiteReviewRequest request, string reviewer, CancellationToken ct)
    {
        var suite = await GetAsync(id, ct);
        if (suite is null) return (null, "Suite not found.");
        var item = suite.Review.FirstOrDefault(r => r.Key == request.Key);
        if (item is null) return (null, "Review item not found in this suite revision.");
        if (!Enum.TryParse<ManualReviewDecisionValue>(request.Decision, out var decision)) return (null, "Unknown decision.");
        return await reviews.RecordAsync(new ManualReviewDecisionRequest
        {
            Module = ManualReviewModules.IntegrationSuites, ScopeKey = suite.SuiteKey, SubjectKey = item.Key, Reviewer = reviewer, Decision = decision, Note = request.Note,
            EvidenceReferences = [.. item.Evidence.Take(ManualReviewRules.MaxEvidence).Select(e => e.Line is { } l ? $"{e.Path}:{l}" : e.Path)],
        }, ct);
    }

    /// <summary>Explicitly authorised execution of the suite's ready contract tests through Contract Testing (its environment safety policy,
    /// credential resolution and Execution Evidence). Tests outside this suite revision are refused; nothing else is executed.</summary>
    public async Task<IntegrationSuiteExecuteResult> ExecuteAsync(Guid id, IntegrationSuiteExecuteRequest request, string initiator, CancellationToken ct)
    {
        if (!request.Authorized) return new(null, "NotAuthorized", "Execution needs the tester's explicit authorisation; nothing was sent.", []);
        var suite = await GetAsync(id, ct);
        if (suite is null) return new(null, "NotFound", "Suite not found.", []);
        var inSuite = suite.Tests.Select(t => t.TestId).ToHashSet();
        var foreign = request.TestIds.Where(t => !inSuite.Contains(t)).ToList();
        if (foreign.Count > 0) return new(null, "Refused", "Only tests of this suite revision can be executed from it.", [.. foreign.Select(f => f.ToString("D"))]);
        if (request.TestIds.Count == 0) return new(null, "Refused", "Choose at least one test.", []);
        var result = await contractTests.RunAsync(new ContractTestRunRequest
        {
            TestIds = request.TestIds, ConfirmMutatingCalls = request.ConfirmMutatingCalls, Name = $"Integration suite {suite.Scope.DisplayName} r{suite.Revision}",
            Environment = new ContractTestEnvironment
            {
                EnvironmentId = request.EnvironmentId, TargetUrl = request.TargetUrl, EnvironmentType = request.EnvironmentType, IsProduction = request.IsProduction,
                ProfileId = request.ProfileId, ContextFingerprint = request.ContextFingerprint,
            },
        }, ct);
        if (result.Run?.RunId is { } runId)
        {
            db.IntegrationSuiteRuns.Add(new IntegrationSuiteRunRecord
            {
                Id = Guid.NewGuid(), SuiteKey = suite.SuiteKey, SuiteId = suite.Id, RunId = runId, Kind = "contract-tests", StartedAt = Now, Initiator = initiator,
                TestIdsJson = JsonSerializer.Serialize(request.TestIds, Json),
            });
            await db.SaveChangesAsync(ct);
        }
        return new(result.Run?.RunId, result.Run?.State.ToString() ?? "NotStarted", result.Run?.Message ?? "No test was ready to run.", result.NotRun);
    }
