using System.Text.Json;
using BirkNext.Api.Services.ExecutionEvidence;
using BirkNext.Api.Services.TestData;
using BirkNext.ContractTesting;
using BirkNext.ExecutionEvidence;
using BirkNext.SourceDomains;
using BirkNext.TestData;

namespace BirkNext.Api.Services.ContractTesting;

/// <summary>
/// Automatic contract test data: for each operation of one contract version, typed synthetic values (<see cref="ContractTestDataRules"/>) for
/// the inputs of its positive test → the materialized request validated by the same contract validator runs use → a versioned key-value set in
/// Test Data (<c>gen-{contract}-v{version}-{operation}</c>; created once, never overwritten) → approved and pinned to the operation's unbound tests
/// only when every required value is contract-derived and certain and the request validates. Anything else stays a draft that names exactly the
/// fields a human must supply or confirm. No second test-data engine or store: Test Data owns the values, Contract Testing owns the binding.
/// Offline and side-effect free towards target systems.
/// </summary>
public sealed class ContractTestDataService(ContractRegistryService registry, ContractTestService tests, IExecutionContractValidator validator,
    TestDataResourceService resources, AuthoredTestDataStore authored, TestDataCatalog catalog, TestDataRegistryStore lifecycle, ILogger<ContractTestDataService> logger,
    TimeProvider? clock = null)
{
    private const string GeneratedNote = "Generated by Contract Testing";
    private static readonly System.Collections.Concurrent.ConcurrentDictionary<string, SemaphoreSlim> Gates = new(StringComparer.Ordinal);

    public async Task<ContractTestDataReport?> GenerateAsync(string key, ContractTestDataRequest request, CancellationToken ct)
    {
        var version = request.Version ?? await registry.LatestVersionAsync(key, ct);
        if (version is not { } v || await registry.RawAsync(key, v, ct) is not { } raw) return null;
        var gate = Gates.GetOrAdd($"{key}@v{v}", _ => new SemaphoreSlim(1, 1));
        await gate.WaitAsync(ct);
        try { return await GenerateLockedAsync(key, v, raw.Text, raw.Document, request, ct); }
        finally { gate.Release(); }
    }

    private async Task<ContractTestDataReport> GenerateLockedAsync(string key, int version, string text, SourceContract doc, ContractTestDataRequest request, CancellationToken ct)
    {
        OpenApiSchemaValidator? schema = null;
        if (doc.Type == SourceContractType.OpenApi && text.Length > 0)
            try { schema = OpenApiSchemaValidator.Parse(text) is { } root ? new OpenApiSchemaValidator(root) : null; } catch (Exception ex) when (ex is JsonException or FormatException) { }
        var views = await tests.ListAsync(key, null, ct);
        var groups = views.Select(x => x.Test).Where(t => t.ContractVersion == version && t.ReviewState != ContractTestReviewState.Retired)
            .Where(t => request.Operations is not { Count: > 0 } || request.Operations.Contains(t.Operation))
            .GroupBy(t => t.Operation, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal);
        var results = new List<ContractTestDataResult>();
        foreach (var group in groups)
        {
            try { results.Add(await OperationAsync(key, version, doc, schema, [.. group], request, ct)); }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                logger.LogWarning(ex, "Contract test data generation failed for one operation of {Contract}", ContractIdentity.ContractRef(key, version));
                results.Add(new() { Operation = group.Key, ContractRef = ContractIdentity.ContractRef(key, version), State = ContractTestDataState.Failed, Summary = $"Generation failed ({ex.GetType().Name}); nothing was bound." });
            }
        }
        return new(key, version, request.Seed, results);
    }

    private async Task<ContractTestDataResult> OperationAsync(string key, int version, SourceContract doc, OpenApiSchemaValidator? schema, List<ContractTestDefinition> group,
        ContractTestDataRequest request, CancellationToken ct)
    {
        var contractRef = ContractIdentity.ContractRef(key, version);
        var operation = group[0].Operation;
        var result = new ContractTestDataResult { Operation = operation, ContractRef = contractRef };
        var positive = group.FirstOrDefault(t => t.Kind == ContractTestKind.Positive);
        var op = doc.Operations.FirstOrDefault(o => o.Name == operation);
        if (positive is null || op is null) return result with { State = ContractTestDataState.NotSupported, Summary = "No positive test for this operation in this contract version." };
        if (positive.Inputs.Count == 0) return result with { State = ContractTestDataState.NoInputs, Summary = "The operation needs no input values." };
        if (group.All(t => t.Binding is not null))
            // Only an approved version can be pinned (ContractTestService.BindAsync), so a bound operation's dataset is approved.
        {
            // The pinned values, so a tester sees what the tests use without regenerating anything.
            var pinned = positive.Binding is { } pb ? authored.Find(pb.Alias)?.Versions.FirstOrDefault(x => x.Version == pb.Version) : null;
            var shown = pinned?.Content.Kind == TestDataResourceKind.KeyValue
                ? pinned.Content.Entries.Select(e => new ContractGeneratedValue(e.Name, positive.Inputs.FirstOrDefault(i => i.Name == e.Name)?.In ?? "", positive.Inputs.FirstOrDefault(i => i.Name == e.Name)?.Required ?? false,
                    e.Type, e.Value is { Length: > 160 } long_ ? long_[..160] + "…" : e.Value, GeneratedValueOrigin.ExistingTestData, GeneratedValueCertainty.Certain, $"pinned {positive.Binding!.Alias}@v{positive.Binding.Version}")).ToList()
                : [];
            return result with { State = ContractTestDataState.AlreadyBound, Approved = true, Dataset = positive.Binding is { } b2 ? $"{b2.Alias}@v{b2.Version}" : null, Values = shown,
                Summary = "Every test of this operation already uses a dataset (kept)." };
        }

        // 1. Values: generated from the contract, or the existing set (never overwritten: it may hold a tester's reviewed values).
        var generated = ContractTestDataRules.Generate(doc, schema, positive, op, request.Seed);
        var alias = Alias($"{ContractTestDataDefaults.AliasPrefix}{key}-v{version}-{operation}");
        var existing = authored.Find(alias);
        var userEdited = existing is not null && (existing.Versions.Count > 1 || existing.Current.ChangeNote?.StartsWith(GeneratedNote, StringComparison.Ordinal) != true);
        var values = generated.Select(g => g.Meta).ToList();
        Dictionary<string, TestDataTypedEntry> entries;
        if (existing is not null && userEdited)
        {
            // A tester's version: its values are used as they are and reported as reviewed values.
            entries = existing.Current.Content.Entries.Where(e => TestDataResourceRules.TypeError(e.Type, e.Value, e.EnumValues) is null).ToDictionary(e => e.Name, StringComparer.Ordinal);
            values = [.. values.Select(m => entries.TryGetValue(m.Name, out var e)
                ? m with { Type = e.Type, Preview = e.Value, Origin = GeneratedValueOrigin.ReviewedUserValue, Certainty = GeneratedValueCertainty.Certain, Rule = $"value in {alias}@v{existing.Current.Version}", Reason = null }
                : m)];
        }
        else
        {
            // Required values as generated (unresolved ones are absent); optional ones only when certain — an uncertain optional value is left out.
            entries = generated.Where(g => g.Entry is not null && (g.Meta.Required || g.Meta.Certainty == GeneratedValueCertainty.Certain))
                .ToDictionary(g => g.Meta.Name, g => g.Entry!, StringComparer.Ordinal);
            if (existing is not null)
            {
                // An earlier generation of this set: the stored values are what tests use. If the generator now proposes other values, the stored
                // set is kept (never replaced silently) and needs a human look.
                var stored = existing.Current.Content.Entries.ToDictionary(e => e.Name, StringComparer.Ordinal);
                if (stored.Count != entries.Count || entries.Any(e => !stored.TryGetValue(e.Key, out var s) || s.Type != e.Value.Type || s.Value != e.Value.Value))
                    values = [.. values.Select(m => m with { Certainty = m.Certainty == GeneratedValueCertainty.Certain ? GeneratedValueCertainty.NeedsReview : m.Certainty,
                        Reason = $"{alias}@v{existing.Current.Version} holds other values than the generator proposes now; it is kept (never overwritten). Review it." })];
                entries = stored;
            }
        }

        // 2. Validation of the request the positive test would send, by the contract validator runs use (not the generator's opinion).
        var (call, missing) = ContractTestRules.Materialize(positive, entries);
        string validation = "NotAssessed";
        var findings = new List<string>();
        var unsupported = new List<string>();
        if (call is not null && await validator.RequestAsync(call with { OperationRef = ContractIdentity.OperationRef(key, version, operation) }, ct) is { } report)
        {
            validation = report.State.ToString();
            findings.AddRange(report.Findings.Take(10).Select(f => $"{f.InstancePath}: {f.Message}"));
            unsupported.AddRange(report.Unsupported.Take(10));
        }
        else if (missing.Count > 0) findings.Add($"Required value(s) not generated: {string.Join(", ", missing)}.");

        // 3. Persist once (a key-value set in Test Data with the provenance of every value).
        var created = false;
        if (existing is null && entries.Count > 0)
        {
            var saved = await resources.CreateAsync(new TestDataResourceDraft
            {
                Alias = alias, Label = $"Generated · {operation}", EnvironmentId = request.EnvironmentId,
                Description = Provenance(contractRef, operation, request.Seed, values, validation),
                AppliesTo = [ContractIdentity.OperationRef(key, version, operation)], ChangeNote = $"{GeneratedNote} from {contractRef} (seed {request.Seed}).",
                Content = new TestDataResourceContent { Kind = TestDataResourceKind.KeyValue, Entries = [.. entries.Values] },
            }, ct);
            if (saved.Saved) created = true;
            else if (authored.Find(alias) is null)
                return result with
                {
                    State = ContractTestDataState.Failed, Values = values, Validation = validation,
                    Findings = [.. findings, .. saved.Validation.Checks.Where(c => c.State == TestDataCheckState.Failed).Select(c => $"Test Data check: {c.Message}")],
                    Summary = $"Not saved in Test Data: {string.Join(" ", saved.Validation.Checks.Where(c => c.State == TestDataCheckState.Failed).Select(c => c.Message).DefaultIfEmpty(saved.Message ?? "refused"))}",
                };
            existing = authored.Find(alias);
        }
        var dataset = existing is null ? null : $"{alias}@v{existing.Current.Version}";
        result = result with { Dataset = dataset, Created = created, Values = values, Validation = validation, Findings = findings, Unsupported = unsupported };

        // 4. Approval: automatic only for a fully contract-derived, schema-valid set that Contract Testing generated; a tester's approval is kept.
        var requiredValues = values.Where(x => x.Required).ToList();
        var certain = requiredValues.All(x => x.Certainty == GeneratedValueCertainty.Certain) && missing.Count == 0;
        var asset = existing is null ? null : catalog.Assets().FirstOrDefault(a => a.Alias == alias && a.SourceId == AuthoredTestDataProvider.ProviderId);
        var approved = asset?.Approval == TestDataApproval.Approved && asset.Version == existing!.Current.Version;
        if (!approved && asset is not null && !userEdited && certain && validation == nameof(ContractValidationState.Valid) && unsupported.Count == 0)
            approved = TestDataCatalogService.Approve(lifecycle, asset, asset, (clock ?? TimeProvider.System).GetUtcNow()) is null;

        // 5. Binding of this operation's tests that use no dataset yet (a tester's binding is never replaced).
        var bound = new List<Guid>();
        if (approved && existing is not null)
            foreach (var t in group.Where(t => t.Binding is null))
                if ((await tests.BindAsync(t.Id, new ContractTestBindRequest(alias, existing.Current.Version), ct)).Test is not null) bound.Add(t.Id);

        var unresolved = requiredValues.Where(x => x.Certainty == GeneratedValueCertainty.Unresolved).Select(x => x.Name).ToList();
        var review = values.Where(x => x.Certainty == GeneratedValueCertainty.NeedsReview && (x.Required || entries.ContainsKey(x.Name))).Select(x => x.Name).ToList();
        var state = approved && bound.Count > 0 ? ContractTestDataState.Bound : unresolved.Count > 0 ? ContractTestDataState.Unresolved : ContractTestDataState.NeedsReview;
        var summary = state switch
        {
            ContractTestDataState.Bound => $"{dataset} generated from the contract, validated ({validation}), approved and pinned to {bound.Count} test(s).",
            ContractTestDataState.Unresolved => $"Needs a value for {string.Join(", ", unresolved)} (not generated: {string.Join(" ", values.Where(x => unresolved.Contains(x.Name)).Select(x => x.Reason).Distinct())}).",
            _ => review.Count > 0 ? $"Confirm {string.Join(", ", review)} in {dataset ?? "Test Data"}, then approve and pin it."
                : validation == nameof(ContractValidationState.Invalid) ? $"The generated request does not validate against {contractRef}: {string.Join("; ", findings.Take(3))}"
                : validation == nameof(ContractValidationState.NotAssessed) ? $"{contractRef} cannot fully validate the request (source-backed contract without its document text, or not evaluated); review {dataset} and approve it."
                : unsupported.Count > 0 ? $"Validation could not evaluate {string.Join(", ", unsupported.Take(3))}; review {dataset} and approve it."
                : approved ? $"{dataset} is approved; every test of this operation already uses a dataset." : $"Review {dataset} and approve it.",
        };
        return result with { State = state, Approved = approved, BoundTests = bound, Summary = summary };
    }

    private static string Provenance(string contractRef, string operation, int seed, List<ContractGeneratedValue> values, string validation) =>
        $"{GeneratedNote} for {operation} from {contractRef}; seed {seed}; synthetic data only (no real persons, no credentials); request validation at generation: {validation}. "
        + string.Join(" ", values.Select(x => $"[{x.Name}: {x.Origin}/{x.Certainty} — {x.Rule}]"));

    /// <summary>A Test Data alias (lower-case, dash-separated, ≤ 60 characters; long names end with a stable hash).</summary>
    public static string Alias(string raw)
    {
        var s = new string([.. raw.ToLowerInvariant().Select(c => char.IsLetterOrDigit(c) ? c : '-')]);
        while (s.Contains("--", StringComparison.Ordinal)) s = s.Replace("--", "-", StringComparison.Ordinal);
        s = s.Trim('-');
        if (s.Length <= 60) return s;
        var hash = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(raw))).ToLowerInvariant()[..8];
        return s[..48].TrimEnd('-') + "-" + hash;
    }
}
