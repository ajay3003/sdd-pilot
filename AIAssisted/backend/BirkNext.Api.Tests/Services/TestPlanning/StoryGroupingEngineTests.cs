    [Fact]
    public void G31_moving_a_story_changes_navigation_only_and_a_confirmed_placement_is_never_moved_silently()
    {
        var input = In(Story("US1", tasks: ["FR-001", "FR-002"]));
        var doc = Apply(new StoryGroupingDocument(),
            new StoryGroupingOperation { Kind = StoryGroupingOperationKind.CreateGroup, Name = "Mottak", Areas = ["Intake"] },
            new StoryGroupingOperation { Kind = StoryGroupingOperationKind.CreateGroup, Name = "Sikkerhet", Areas = ["Access"] });
        var moved = Apply(doc, new StoryGroupingOperation { Kind = StoryGroupingOperationKind.PlaceStory, StoryKey = "spec.md#us1", GroupId = "g-sikkerhet", SuggestedArea = "Intake" });
        var before = One(input, doc); var after = One(input, moved);
        after.GroupId.Should().Be("g-sikkerhet");
        after.State.Should().Be(GroupingState.Confirmed);
        after.Requirements.Should().BeEquivalentTo(before.Requirements, "moving a story never changes its requirement links");

        // A new link tips the suggestion to Quality: the confirmed placement stays, and the change is reported.
        var relinked = Apply(moved, Op(StoryGroupingOperationKind.AddLink, req: "FR-014"), Op(StoryGroupingOperationKind.AddLink, req: "FR-015"), Op(StoryGroupingOperationKind.AddLink, req: "FR-015a"));
        var p = One(input, relinked);
        p.SuggestedArea.Should().Be("Quality");
        p.GroupId.Should().Be("g-sikkerhet");
        p.SuggestionChanged.Should().BeTrue("«Grupperingsforslaget er endret» is shown; nothing moves until a person decides");
    }

