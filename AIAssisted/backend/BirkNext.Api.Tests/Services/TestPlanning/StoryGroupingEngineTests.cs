    [Fact]
    public void G33_merge_split_delete_and_restore_source_navigation_keep_stories_and_decisions()
    {
        var doc = Apply(new StoryGroupingDocument(),
            new StoryGroupingOperation { Kind = StoryGroupingOperationKind.CreateGroup, Name = "A", Areas = ["Intake"] },
            new StoryGroupingOperation { Kind = StoryGroupingOperationKind.CreateGroup, Name = "B", Areas = ["Quality"] },
            new StoryGroupingOperation { Kind = StoryGroupingOperationKind.PlaceStory, StoryKey = "s1", GroupId = "g-b" },
            new StoryGroupingOperation { Kind = StoryGroupingOperationKind.PlaceStory, StoryKey = "s2", GroupId = "g-b" },
            Op(StoryGroupingOperationKind.AddLink, story: "s1", req: "FR-001"));
        FluentActions.Invoking(() => Apply(doc, new StoryGroupingOperation { Kind = StoryGroupingOperationKind.DeleteGroup, GroupId = "g-b" }))
            .Should().Throw<StoryGroupingEngine.GroupingRefusal>("a group with stories is never deleted").Which.Code.Should().Be("group-not-empty");

        var merged = Apply(doc, new StoryGroupingOperation { Kind = StoryGroupingOperationKind.MergeGroups, GroupId = "g-b", TargetGroupId = "g-a" });
        merged.Groups.Should().ContainSingle(g => g.Id == "g-a" && g.FunctionalAreas.SequenceEqual(new[] { "Intake", "Quality" }));
        merged.Placements.Should().OnlyContain(p => p.GroupId == "g-a").And.HaveCount(2, "no duplicate memberships");

        var split = Apply(merged, new StoryGroupingOperation { Kind = StoryGroupingOperationKind.SplitGroup, GroupId = "g-a", Name = "C", StoryKeys = ["s2"], Areas = ["Quality"] });
        split.Placements.Single(p => p.StoryKey == "s2").GroupId.Should().Be("g-c");
        split.Placements.Single(p => p.StoryKey == "s1").GroupId.Should().Be("g-a");

        var restored = Apply(split, new StoryGroupingOperation { Kind = StoryGroupingOperationKind.RestoreSourceNavigation });
        restored.Placements.Should().BeEmpty();
        restored.Groups.Should().HaveCount(2, "groups are kept");
        restored.Decisions.Should().BeEquivalentTo(doc.Decisions, "requirement decisions are never touched by grouping operations");

        var emptied = Apply(restored, new StoryGroupingOperation { Kind = StoryGroupingOperationKind.DeleteGroup, GroupId = "g-c" });
        emptied.Groups.Should().ContainSingle(g => g.Id == "g-a");
    }

