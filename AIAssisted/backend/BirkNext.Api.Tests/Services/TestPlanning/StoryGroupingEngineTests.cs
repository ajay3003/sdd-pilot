    // ── Review operations ─────────────────────────────────────────────────────────────────────────────────────────

    private static readonly HashSet<string> Known = new(["FR-001", "FR-002", "FR-003", "FR-014", "FR-015", "FR-015A", "FR-040"], StringComparer.OrdinalIgnoreCase);
    private static StoryGroupingDocument Apply(StoryGroupingDocument doc, params StoryGroupingOperation[] ops) =>
        StoryGroupingEngine.Apply(doc, ops, "tester", DateTimeOffset.Parse("2026-11-24T12:00:00Z"), Known.Contains, name => "g-" + name.ToLowerInvariant().Replace(' ', '-'));
    private static StoryGroupingOperation Op(StoryGroupingOperationKind kind, string? story = "spec.md#us1", string? req = null, string? newReq = null, string? reason = null) =>
        new() { Kind = kind, StoryKey = story, RequirementId = req, DisplayId = req, NewRequirementId = newReq, NewDisplayId = newReq, Reason = reason };

    [Fact]
    public void G20_add_a_real_requirement_changes_the_suggestion_and_a_fictional_one_is_refused()
    {
        var input = In(Story("US1", tasks: ["FR-001", "FR-014"]));
        One(input).State.Should().Be(GroupingState.NeedsGrouping);
        var doc = Apply(new StoryGroupingDocument(), Op(StoryGroupingOperationKind.AddLink, req: "FR-015a", reason: "Flagging is the point"));
        var after = One(input, doc);
        after.SuggestedArea.Should().Be("Quality", "the added link tips the balance");
        after.Requirements.Single(r => r.RequirementId == "FR-015A").Basis.Should().Be(StoryLinkBasis.HumanConfirmed);
        doc.History.Should().ContainSingle(h => h.Action == "La til kravkobling" && h.By == "tester");
        FluentActions.Invoking(() => Apply(doc, Op(StoryGroupingOperationKind.AddLink, req: "FR-999"))).Should().Throw<StoryGroupingEngine.GroupingRefusal>().Which.Code.Should().Be("unknown-requirement");
        FluentActions.Invoking(() => Apply(doc, Op(StoryGroupingOperationKind.AddLink, req: "fr-015A"))).Should().Throw<StoryGroupingEngine.GroupingRefusal>().Which.Code.Should().Be("duplicate-link");
    }

    [Fact]
    public void G21_confirm_reject_and_restore_a_suggestion_and_a_rejection_survives_a_reload()
    {
        var input = In(Story("US1"), suggestions: ["FR-014"]);
        var confirmed = Apply(new StoryGroupingDocument(), Op(StoryGroupingOperationKind.ConfirmLink, req: "FR-014"));
        One(input, confirmed).Requirements.Single().Basis.Should().Be(StoryLinkBasis.HumanConfirmed);
        One(input, confirmed).SuggestedArea.Should().Be("Quality");

        var rejected = Apply(new StoryGroupingDocument(), Op(StoryGroupingOperationKind.RejectLink, req: "FR-014", reason: "Wrong rule"));
        var r = One(input, rejected).Requirements.Single();
        r.Rejected.Should().BeTrue("the same unchanged suggestion is shown as rejected, never as a fresh suggestion");
        r.Established.Should().BeFalse();
        var restored = Apply(rejected, Op(StoryGroupingOperationKind.RestoreLink, req: "FR-014"));
        One(input, restored).Requirements.Single().Rejected.Should().BeFalse();
        restored.Decisions.Should().HaveCount(2, "history is kept");
    }

    [Fact]
    public void G22_remove_and_replace_only_apply_to_links_a_person_added_and_replace_is_one_recorded_change()
    {
        var input = In(Story("US1", named: ["FR-015"]));
        var added = Apply(new StoryGroupingDocument(), Op(StoryGroupingOperationKind.AddLink, req: "FR-001"));
        var replaced = Apply(added, Op(StoryGroupingOperationKind.ReplaceLink, req: "FR-001", newReq: "FR-002", reason: "Meant identity lookup"));
        var p = One(input, replaced);
        p.Requirements.Select(x => x.RequirementId).Should().BeEquivalentTo(["FR-015", "FR-002"]);
        replaced.Decisions.Should().Contain(d => d.RequirementId == "FR-002" && d.ReplacementOf == "FR-001");
        replaced.History.Should().ContainSingle(h => h.Action == "Erstattet kravkobling");
        replaced.Revision.Should().Be(added.Revision + 1);

        FluentActions.Invoking(() => Apply(replaced, Op(StoryGroupingOperationKind.RemoveLink, req: "FR-015")))
            .Should().Throw<StoryGroupingEngine.GroupingRefusal>("a source-stated link cannot be removed").Which.Code.Should().Be("not-manual");
        FluentActions.Invoking(() => Apply(replaced, Op(StoryGroupingOperationKind.ReplaceLink, req: "FR-015", newReq: "FR-015a")))
            .Should().Throw<StoryGroupingEngine.GroupingRefusal>().Which.Code.Should().Be("not-manual");

        var removed = Apply(replaced, Op(StoryGroupingOperationKind.RemoveLink, req: "FR-002"));
        One(input, removed).Requirements.Select(x => x.RequirementId).Should().Equal("FR-015");
    }

    [Fact]
    public void G23_a_disputed_source_link_keeps_its_evidence_and_the_correction_sits_beside_it()
    {
        var input = In(Story("US1", named: ["FR-015"]));
        var doc = Apply(new StoryGroupingDocument(), new StoryGroupingOperation
        {
            Kind = StoryGroupingOperationKind.DisputeLink, StoryKey = "spec.md#us1", RequirementId = "FR-015", DisplayId = "FR-015", NewRequirementId = "FR-015a",
            NewDisplayId = "FR-015a", Reason = "The story is about attendance above plan", ExcludeFromGrouping = true,
        });
        var p = One(input, doc);
        var source = p.Requirements.Single(r => r.RequirementId == "FR-015");
        source.Basis.Should().Be(StoryLinkBasis.SourceExplicit, "the source still says FR-015");
        source.Disputed.Should().BeTrue();
        source.Established.Should().BeFalse("left out of grouping inference on request");
        source.Evidence.Should().Contain(e => e.Kind == "story");
        p.Requirements.Single(r => r.RequirementId == "FR-015A").Basis.Should().Be(StoryLinkBasis.HumanConfirmed);
        FluentActions.Invoking(() => Apply(doc, Op(StoryGroupingOperationKind.DisputeLink, req: "FR-015")))
            .Should().Throw<StoryGroupingEngine.GroupingRefusal>("a dispute needs a reason").Which.Code.Should().Be("missing-reason");
    }

    [Fact]
    public void G24_undo_is_a_compensating_decision_that_keeps_history()
    {
        var input = In(Story("US1"));
