    {
        var profiles = StoryGroupingEngine.Profiles(RealInputs(), Real.Value.Sections, null);
        profiles.Should().HaveCount(8);
        profiles.Should().OnlyContain(p => p.Explanation.Length > 0);
        var us2 = profiles.Single(p => p.StoryKey == Real.Value.Evidence.Stories.Single(s => s.StoryId == "US2").Key);
        if (us2.Requirements.Count == 0) us2.State.Should().Be(GroupingState.NoRequirements, "US2 has no source, scenario or task link in this version: «Uten krav», never guessed");
        else us2.Explanation.Should().NotBeNullOrWhiteSpace();
        foreach (var p in profiles.Where(p => p.SuggestedArea is not null))
        {
            p.Requirements.Where(r => r.Established && !r.CrossCutting && r.Area == p.SuggestedArea).Should().NotBeEmpty("a suggestion names its source-backed requirements");
            Real.Value.Sections.Sections.Select(s => s.Title).Should().Contain(p.SuggestedArea!, "an area is a real section title");
        }
    }

    [Fact]
    public void G04_real_grouping_report_is_written_when_requested()
    {
        var profiles = StoryGroupingEngine.Profiles(RealInputs(), Real.Value.Sections, null);
        var stories = Real.Value.Evidence.Stories.ToDictionary(s => s.Key);
        var report = new StringBuilder();
        report.AppendLine("# SkoleService US1–US8 — FR-based grouping (generated by StoryGroupingEngineTests.G04)").AppendLine();
        report.AppendLine("Source: Fixtures/m2lb-specs/SkoleService/specs/001-skoleservice/spec.md + tasks.md (M2LB (8), copied unchanged). No reviewed decisions applied.").AppendLine();
        report.AppendLine("| Story | Linked FRs (basis → section) | Suggested primary area | Secondary areas | State | Explanation |").AppendLine("|---|---|---|---|---|---|");
        foreach (var p in profiles)
        {
            var s = stories[p.StoryKey];
            var links = p.Requirements.Count == 0 ? "—" : string.Join("<br>", p.Requirements.Select(r => $"{r.DisplayId} ({r.Basis}{(r.CrossCutting ? ", tverrgående" : "")}) → {r.Area}"));
            report.AppendLine($"| {s.StoryId} {s.Title.Replace("|", "/")} | {links} | {p.SuggestedArea ?? "—"} | {string.Join("; ", p.SecondaryAreas)} | {p.State} | {p.Explanation.Replace("|", "/")} |");
        }
        var text = report.ToString();
        text.Should().Contain("| US1 ");
        if (Environment.GetEnvironmentVariable("BIRKNEXT_WRITE_GROUPING_REPORT") is "1")
            File.WriteAllText(Path.Combine(Fixtures(), "story-grouping-report.md"), text);
    }

    private static string Fixtures([CallerFilePath] string here = "") => Path.Combine(Path.GetDirectoryName(here)!, "Fixtures");

