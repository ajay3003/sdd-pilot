    private static CoverageUserStory Story(string id, string[]? named = null, string[]? tasks = null) => new()
    {
        Key = $"spec.md#{id.ToLowerInvariant()}", StoryId = id, Title = id, SpecificationPath = "spec.md", NamedRequirements = [.. named ?? []],
        TaskRequirements = [.. (tasks ?? []).Select((t, i) => new StoryTaskRequirement(t, $"T{i}", $"[{id}] task naming {t}", "tasks.md", i + 1))],
    };

    private static StoryGroupingEngine.StoryInputs In(CoverageUserStory s, string[]? scenarios = null, string[]? suggestions = null) =>
        new(s, [.. (scenarios ?? []).Select(x => (x, "scenario"))], [], [.. (suggestions ?? []).Select(x => (x, "rule"))]);

    private static StoryGroupingProfile One(StoryGroupingEngine.StoryInputs input, StoryGroupingDocument? doc = null) =>
        StoryGroupingEngine.Profiles([input], Sections, doc).Single();

    [Fact]
