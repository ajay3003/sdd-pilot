using System.Text.Json.Serialization;

namespace BirkNext.Integrations;

// ─────────────────────────────────────────────────────────────────────────────────────────────────────────────────────
// Altinn app testing: the contract of one Altinn 3 app as BirkNext knows it, and the tester's ID-porten TEST sign-in state. The contract
// comes from two read-only sources — the app's repository uploaded to Source Analysis (authoritative) and the app's public TT02 metadata —
// and is never guessed: a part that neither source supplies stays missing and keeps execution Not ready. No URL, secret, token or payload
// is representable here.
// ─────────────────────────────────────────────────────────────────────────────────────────────────────────────────────

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum AltinnContractSourceKind { SourceAnalysisSnapshot, PublicTt02Metadata, DeployedOpenApi }

/// <summary>
/// What BirkNext may do with the app's process, judged for the one operation it intends (a bounded process/next from the form's data task),
/// not for the whole BPMN topology. <see cref="ConfirmedForCurrentOperation"/>: the task, the operation and its observable result are
/// established and execution is bounded. <see cref="Partial"/>: a specific fact for the operation is missing. <see cref="NotConfirmed"/>: no
/// trustworthy static or deployed process evidence. <see cref="Conflict"/>: the sources disagree.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter))]
public enum AltinnProcessContractStatus { ConfirmedForCurrentOperation, Partial, NotConfirmed, Conflict }

/// <summary>A process task as the deployed app's generated OpenAPI document declares it (app-lib lists every BPMN task and service task;
/// gateways and events are not listed). <see cref="Actions"/> are the task's declared Altinn actions.</summary>
public sealed record AltinnDeclaredProcessTask(string TaskId, string Name, string TaskType, IReadOnlyList<string> Actions);

/// <summary>A data type and the process task it belongs to, as the deployed OpenAPI document declares it.</summary>
public sealed record AltinnDataTypeTask(string DataTypeId, string? TaskId);

/// <summary>
/// Normalized facts from the app's own deployed OpenAPI document (<c>v1/customOpenapi.json</c>, generated by app-lib from the deployed
/// process and metadata and read anonymously from the TT02 app host). Only these facts are kept — never the document.
/// </summary>
public sealed record AltinnDeployedProcessContract
{
    public string Document { get; init; } = "";
    /// <summary>SHA-256 (hex) of the document as read.</summary>
    public string Fingerprint { get; init; } = "";
    public string? AppLibVersion { get; init; }
    /// <summary>True when the generated process-task table was found; without it the document says nothing about tasks.</summary>
    public bool TaskInventoryFound { get; init; }
    public IReadOnlyList<AltinnDeclaredProcessTask> Tasks { get; init; } = [];
    public IReadOnlyList<AltinnDataTypeTask> DataTypeTasks { get; init; } = [];
    public bool ProcessNextDeclared { get; init; }
    public string? ProcessNextMethod { get; init; }
    public bool ProcessNextBodyRequired { get; init; }
    public IReadOnlyList<string> ProcessNextBodyFields { get; init; } = [];
    /// <summary>The schema of the successful (200) process/next response, e.g. AppProcessState.</summary>
    public string? ProcessNextResponseSchema { get; init; }
    /// <summary>The top-level fields of that response schema (e.g. currentTask, ended, endEvent, actions).</summary>
    public IReadOnlyList<string> ProcessStateFields { get; init; } = [];
    public IReadOnlyList<string> Notes { get; init; } = [];
}

/// <summary>
/// The process contract as BirkNext uses it: which evidence supports the intended operation, the tasks it will transition from (in order),
/// the execution bound and the post-condition that counts as success. <see cref="TopologyKnown"/> says whether the full BPMN graph is known
/// (only from a parsed static process.bpmn); the operation can be confirmed without it.
/// </summary>
public sealed record AltinnProcessAssessment
{
    public AltinnProcessContractStatus Status { get; init; } = AltinnProcessContractStatus.NotConfirmed;
    public string Summary { get; init; } = "";
    public IReadOnlyList<string> Sources { get; init; } = [];
    public int? DeclaredTaskCount { get; init; }
    public IReadOnlyList<AltinnDeclaredProcessTask> PlannedTasks { get; init; } = [];
    public string Operation { get; init; } = "";
    /// <summary>process/next calls the plan needs (0 when not confirmed).</summary>
    public int Transitions { get; init; }
    /// <summary>The execution policy's maximum process/next calls per run.</summary>
    public int MaxTransitions { get; init; }
    public string ExpectedPostCondition { get; init; } = "";
    public string StaticDefinition { get; init; } = "";
    public bool TopologyKnown { get; init; }
    public IReadOnlyList<string> Reasons { get; init; } = [];
    public bool Confirmed => Status == AltinnProcessContractStatus.ConfirmedForCurrentOperation;
}

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum AltinnContractPartKind { ApplicationMetadata, FormDataType, DataModelSchema, ProcessDefinition }

/// <summary>One field of the form data model, flattened from its schema (dot-separated path, JSON schema type/format).</summary>
public sealed record AltinnSchemaField(string Path, string Type, string? Format, bool Required);

/// <summary>A process task in order. <see cref="TaskType"/> is the Altinn task type (data, confirmation, signing, payment, feedback).</summary>
public sealed record AltinnProcessTask(string TaskId, string TaskType);

/// <summary>What one source said about the app. Null parts were not supplied by that source.</summary>
public sealed record AltinnContractSnapshot
{
    public AltinnContractSourceKind Source { get; init; }
    public string AppId { get; init; } = "";
    public DateTimeOffset CapturedAt { get; init; }
    /// <summary>SHA-256 over the source documents (hex), so a later run can tell which contract it used.</summary>
    public string Fingerprint { get; init; } = "";
    public IReadOnlyList<string> Documents { get; init; } = [];
    public bool HasApplicationMetadata { get; init; }
    /// <summary>The single data type the app binds its form model to (an app-logic data type). Null when absent or ambiguous.</summary>
    public string? FormDataTypeId { get; init; }
    public IReadOnlyList<string> FormDataTypeCandidates { get; init; } = [];
    public IReadOnlyList<string> AllowedContentTypes { get; init; } = [];
    public IReadOnlyList<AltinnSchemaField>? Fields { get; init; }
    public IReadOnlyList<AltinnProcessTask>? ProcessTasks { get; init; }
    /// <summary>The process task the form data type belongs to (application metadata dataTypes[].taskId).</summary>
    public string? FormDataTaskId { get; init; }
    /// <summary>For public TT02 metadata: the facts of the app's deployed OpenAPI document, when it was read.</summary>
    public AltinnDeployedProcessContract? DeployedProcess { get; init; }
    public IReadOnlyList<string> Notes { get; init; } = [];
    /// <summary>From the form schema (@xsdRootElement, default @xsdNamespaces, ElementFormDefault): how the form is written as XML.</summary>
    public string? XmlRootElement { get; init; }
    public string? XmlNamespace { get; init; }
    public bool XmlElementsQualified { get; init; }
    /// <summary>For a Source Analysis source: the snapshot and archive the app files were read from.</summary>
    public Guid? SourceSnapshotId { get; init; }
    public string? SourceArchive { get; init; }
}

/// <summary>Both sources as stored with the Integration Quality Review message-flow configuration of one environment.</summary>
public sealed record AltinnAppContractRecord(AltinnContractSnapshot? SourceAnalysis, AltinnContractSnapshot? PublicMetadata);

/// <summary>A Source Analysis snapshot that contains the source of one or more Altinn apps.</summary>
public sealed record AltinnSourceCandidate(Guid SnapshotId, string ArchiveName, DateTimeOffset AnalyzedAt, IReadOnlyList<string> AppIds);

public sealed record AltinnContractPartStatus(AltinnContractPartKind Part, bool Present, AltinnContractSourceKind? Source, string Detail);

/// <summary>A domain field the submission needs, and whether the app's schema really contains it (exact path and compatible type).</summary>
public sealed record AltinnFieldBinding(string Key, string Label, string ExpectedPath, string ExpectedType, bool Present, string Detail);

/// <summary>The effective contract: per part, the Source Analysis app source wins over the public metadata. Complete only when nothing is missing.</summary>
public sealed record AltinnAppContractView
{
    public string EnvironmentId { get; init; } = "";
    /// <summary>The app id configured in Integration Quality Review (Altinn test configuration).</summary>
    public string? ConfiguredAppId { get; init; }
    public bool AppApproved { get; init; }
    public string AppDetail { get; init; } = "";
    public string? FormDataTypeId { get; init; }
    public IReadOnlyList<AltinnContractPartStatus> Parts { get; init; } = [];
    public IReadOnlyList<AltinnFieldBinding> Bindings { get; init; } = [];
    /// <summary>The effective form schema fields (from the same source as the form data type).</summary>
    public IReadOnlyList<AltinnSchemaField> Fields { get; init; } = [];
    /// <summary>How the form data is submitted: application/json when the data type allows it, otherwise application/xml written from the
    /// schema's own root element and namespace. Null when neither is possible.</summary>
    public string? SubmissionContentType { get; init; }
    public string? XmlRootElement { get; init; }
    public string? XmlNamespace { get; init; }
    public bool XmlElementsQualified { get; init; }
    /// <summary>The tasks the process plan transitions from, in order (empty unless the process contract is confirmed for the operation).</summary>
    public IReadOnlyList<AltinnProcessTask> ProcessTasks { get; init; } = [];
    public AltinnProcessAssessment Process { get; init; } = new();
    public IReadOnlyList<AltinnSchemaField> RequiredUnboundFields { get; init; } = [];
    public IReadOnlyList<AltinnContractSnapshot> Sources { get; init; } = [];
    /// <summary>Source Analysis snapshots of this environment that contain the configured app's source.</summary>
    public IReadOnlyList<AltinnSourceCandidate> SourceCandidates { get; init; } = [];
    public bool Complete { get; init; }
    public IReadOnlyList<string> Missing { get; init; } = [];
}

/// <summary>The tester's ID-porten TEST sign-in for one environment. The token itself never leaves the backend.</summary>
public sealed record AltinnSignInStatus
{
    public bool Configured { get; init; }
    public IReadOnlyList<string> ConfigurationProblems { get; init; } = [];
    public bool SignedIn { get; init; }
    public DateTimeOffset? ExpiresAt { get; init; }
    public string Detail { get; init; } = "";
}

/// <summary>Where the browser goes to sign in. Built by the backend from approved ID-porten TEST endpoints only.</summary>
public sealed record AltinnSignInStart(string AuthorizationUrl, DateTimeOffset ExpiresAt);

/// <summary>One approved synthetic TEST reporter as the UI may see it: the alias and its readiness. The TestID identifier never leaves the backend.</summary>
public sealed record AltinnSyntheticReporterView(string Alias, string Label, bool Valid, string Detail);

/// <summary>
/// Readiness of unattended reporter authentication (ID-porten TEST headless login for a configured synthetic TestID reporter, exchanged for an
/// Altinn TT02 token). Each prerequisite is reported on its own; a secret is reported only as available or missing, never by value.
/// </summary>
public sealed record AltinnUnattendedStatus
{
    public bool ProviderEnabled { get; init; }
    public bool ClientConfigured { get; init; }
    public bool RedirectConfigured { get; init; }
    public bool SecretAvailable { get; init; }
    public IReadOnlyList<AltinnSyntheticReporterView> Reporters { get; init; } = [];
    public bool AppPolicyConfirmed { get; init; }
    public string AppPolicyDetail { get; init; } = "";
    public bool ProductionBlocked { get; init; }
    /// <summary>True when every unattended prerequisite above is met (the app policy is reported separately and gates submissions).</summary>
    public bool Ready { get; init; }
    public IReadOnlyList<string> Problems { get; init; } = [];
}
