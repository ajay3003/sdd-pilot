    private IRenderedComponent<GeneratedDocumentationHealthPanel> RenderWith(GeneratedDocumentationDiagnosticRun run, out FakeApi api)
    {
        var fake = new FakeApi(run);
        api = fake;
        return Render<GeneratedDocumentationHealthPanel>(p => p.Add(x => x.Api, fake));
    }

