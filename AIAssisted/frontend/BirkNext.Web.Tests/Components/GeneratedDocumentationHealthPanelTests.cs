    [Fact]
    public async Task The_request_carries_the_imported_project_and_its_selected_artifacts_only()
    {
        var artifact = new ExplorerArtifact("a1", WorkspaceArtifactType.Specification, "spec.md", "spec.md", "shop/orders/specs/001-orders/spec.md",
            ExplorerArtifactSource.Workspace, "ProjectImport", 1, 1, "Draft", ExplorerArtifactCurrentness.Current, null);
        var context = new Mock<IArtifactExplorerContext>();
        context.SetupGet(c => c.CurrentScope).Returns(ProjectImportScope.For("import-123"));
        context.Setup(c => c.GetStateAsync(It.IsAny<WorkspaceArtifactType>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync((WorkspaceArtifactType role, CancellationToken _) => role == WorkspaceArtifactType.Specification
                ? new ArtifactExplorerState(role, ExplorerArtifactStatus.Loaded, null, "Shop", [artifact], artifact, ExplorerSelectionReason.Explicit, "# Spec\n\nGET /orders\n")
                : new ArtifactExplorerState(role, ExplorerArtifactStatus.Empty, null, "Shop", []));
        var inputs = await TraceabilityInputs.ResolveAsync(context.Object);
        var request = GeneratedDocumentationApiService.Request(inputs);
        request.ProjectImportId.Should().Be("import-123");
        request.AuthoredArtifacts.Should().ContainSingle();
        request.AuthoredArtifacts[0].Role.Should().Be("Specification");
        request.AuthoredArtifacts[0].SourcePath.Should().Be("shop/orders/specs/001-orders/spec.md");
        GeneratedDocumentationApiService.Request(null).AuthoredArtifacts.Should().BeEmpty();
    }

    [Fact]
    public void Source_Analysis_summary_links_to_the_diagnostic_and_handles_older_snapshots()
    {
        var older = Render<GeneratedDocumentationSourceSummary>(p => p.Add(x => x.Snapshot, new IqrSourceSnapshot()));
        older.Find("[data-testid=sa-generated-docs-missing]");
        older.Find("[data-testid=sa-generated-docs-link]").GetAttribute("href").Should().Be("generated-documentation-health");

        var none = Render<GeneratedDocumentationSourceSummary>(p => p.Add(x => x.Snapshot, new IqrSourceSnapshot { GeneratedDocumentation = new GeneratedDocumentationSnapshot() }));
        none.Find("[data-testid=sa-generated-docs-empty]").TextContent.Should().Be(GeneratedDocumentationText.EmptyState);

        var stale = new GeneratedDocumentationSnapshot
        {
            Documents = [new GeneratedDocumentationEvidence { EvidenceId = "d", Origin = DocumentationOrigin.Generated }],
            Modules = [new GeneratedDocumentationModule { ModuleId = "m", Freshness = GeneratedDocumentationFreshnessStatus.Stale, GeneratorIds = ["w"] }],
        };
        var some = Render<GeneratedDocumentationSourceSummary>(p => p.Add(x => x.Snapshot, new IqrSourceSnapshot { GeneratedDocumentation = stale }));
        some.Find("[data-testid=sa-generated-docs-status]").TextContent.Should().Be("Review suggested", "staleness is a candidate for review, never a verdict");

        // An unresolved source correlation alone stays neutral and is not counted as a consistency candidate.
        var unresolved = new GeneratedDocumentationSnapshot
        {
            Documents = [new GeneratedDocumentationEvidence { EvidenceId = "d", Origin = DocumentationOrigin.Generated }],
            Modules = [new GeneratedDocumentationModule { ModuleId = "m", Freshness = GeneratedDocumentationFreshnessStatus.NotEnoughEvidence, GeneratorIds = ["w"] }],
            Drift = [Drift("drift:9", CrossArtifactDriftType.DocumentationDrift, "m", "ConnectionStrings:ServiceBus", DriftDifferenceKind.MissingOnRight) with { Family = "Configuration keys" }],
        };
        var neutral = Render<GeneratedDocumentationSourceSummary>(p => p.Add(x => x.Snapshot, new IqrSourceSnapshot { GeneratedDocumentation = unresolved }));
        neutral.Find("[data-testid=sa-generated-docs-status]").TextContent.Should().Be("Detected");
        neutral.Find("[data-testid=sa-generated-docs-differences] dd").TextContent.Should().Be("0");
        neutral.Find("[data-testid=sa-generated-docs-unresolved] dd").TextContent.Should().Contain("1").And.Contain("not drift");
    }

    [Fact]
    public void Presentation_filters_and_tones_are_fact_based()
    {
        var run = ReadyRun();
        GeneratedDocumentationPresentation.Count(run, GeneratedDocumentationFilter.All).Should().Be(3);
        GeneratedDocumentationPresentation.Count(run, GeneratedDocumentationFilter.Fresh).Should().Be(1);
        GeneratedDocumentationPresentation.Count(run, GeneratedDocumentationFilter.SourceDiscrepancies).Should().Be(1);
        GeneratedDocumentationPresentation.Tone(GeneratedDocumentationHealthStatus.Warning).Should().Be("partial");
        GeneratedDocumentationPresentation.Tone(GeneratedDocumentationHealthStatus.Fail).Should().Be("attention");
        GeneratedDocumentationPresentation.Tone(GeneratedDocumentationFreshnessStatus.Stale).Should().Be("partial", "staleness needs review; it is never red");
        GeneratedDocumentationPresentation.DriftFor(run, run.Modules[0]).Select(d => d.Id).Should().Equal("drift:1", "drift:2");
        GeneratedDocumentationPresentation.UnresolvedFor(run, run.Modules[0]).Select(d => d.Id).Should().Equal("drift:3");
        GeneratedDocumentationPresentation.Count(run, GeneratedDocumentationFilter.UnableToCompare).Should().Be(3);
        // Warning colour only for comparable inconsistency; unresolved, unable to compare and not assessed stay neutral.
        GeneratedDocumentationPresentation.Tone(GeneratedComparisonState.PotentialInconsistency).Should().Be("partial");
        GeneratedDocumentationPresentation.Tone(GeneratedComparisonState.SourceCorrelationUnresolved).Should().Be("muted");
        GeneratedDocumentationPresentation.Tone(GeneratedComparisonState.UnableToCompare).Should().Be("muted");
        GeneratedDocumentationPresentation.Tone(GeneratedConsistencyCategory.SourceCorrelationUnresolved).Should().Be("muted");
        GeneratedDocumentationPresentation.Tone(new ExpectedGeneratedDocument("message-bus.md", GeneratedDocumentKind.Messaging, false, true, "") { State = ExpectedDocumentState.ApplicabilityNotEstablished }).Should().Be("muted");
        GeneratedDocumentationPresentation.Tone(new ExpectedGeneratedDocument("message-bus.md", GeneratedDocumentKind.Messaging, false, true, "") { State = ExpectedDocumentState.RequiredMissing }).Should().Be("partial");
    }

