                review: GeneratedDocumentationReviewState.ReviewSuggested),
            Module("billing", GeneratedDocumentationHealthStatus.Pass, GeneratedDocumentationFreshnessStatus.Current),
            Module("catalog", GeneratedDocumentationHealthStatus.Partial, GeneratedDocumentationFreshnessStatus.Unknown, generator: false),
        ],
        Generators = [new GeneratorWorkflowEvidence { Id = "workflow:x", Type = GeneratorType.AgentWorkflow, GeneratorName = "doc-writer", Path = ".claude/skills/doc-writer/SKILL.md", Role = "Agent skill definition", Basis = "Declares generated-docs/ as an output" }],
        Drift = [Drift("drift:1", CrossArtifactDriftType.DocumentationDrift, "module:orders", "GET /invoices"), Drift("drift:2", CrossArtifactDriftType.SpecificationDrift, "module:orders", "GET /refunds"),
            Drift("drift:3", CrossArtifactDriftType.DocumentationDrift, "module:orders", "ConnectionStrings:ServiceBus", DriftDifferenceKind.MissingOnRight) with { Family = "Configuration keys" }],
        Authored = new AuthoredComparisonState(true, "Compared.", ["Specification · spec.md"]),
