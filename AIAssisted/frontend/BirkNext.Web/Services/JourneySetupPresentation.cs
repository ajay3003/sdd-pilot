using BirkNext.Integrations;

namespace BirkNext.Web.Services;

/// <summary>
/// Labels and context-preserving actions for the shared Guided Setup steps. Every action opens the owner of the fix with the exact context it
/// already knows (the journey's own configured integration, its binding editor, its contract pair, its provider) — never a generic landing page
/// when the context is known. Presentation only: the steps come from <see cref="JourneySetupModel"/>.
/// </summary>
public static class JourneySetupPresentation
{
    /// <summary>What a step offers: a link to the owner (<paramref name="Href"/>) or an in-page command the host page performs (<paramref name="Command"/>).</summary>
    public sealed record StepAction(string Label, string? Href, string? Note, string? Command = null);

    public static string Status(JourneySetupStepStatus status) => status switch
    {
        JourneySetupStepStatus.Ready => "Ready",
        JourneySetupStepStatus.NeedsAction => "Needs action",
        JourneySetupStepStatus.Blocked => "Blocked",
        JourneySetupStepStatus.Partial => "Partial",
        JourneySetupStepStatus.Optional => "Optional",
        _ => "Not applicable",
    };

    /// <summary>Pill tone (the label always carries the meaning; colour is never the only signal).</summary>
    public static string Tone(JourneySetupStepStatus status) => status switch
    {
        JourneySetupStepStatus.Ready => "ready",
        JourneySetupStepStatus.Optional or JourneySetupStepStatus.NotApplicable => "muted",
        _ => "attention",
    };

    public static string YesNo(bool value) => value ? "Yes" : "No";

    /// <summary>"Rapportmottak · 5 of 8 required setup steps ready".</summary>
    public static string Progress(JourneySetupView setup) =>
        $"{setup.JourneyName} · {setup.RequiredReady} of {setup.RequiredSteps} required setup step{(setup.RequiredSteps == 1 ? "" : "s")} ready";

    /// <summary>"Setup complete · not runtime verified" — never "passed" or "ready for production".</summary>
    public static string Completion(JourneySetupView setup) => setup.SetupComplete ? "Setup complete · not runtime verified" : $"Next action: {setup.NextAction}";

    /// <summary>The first configured integration a journey matched (the context every integration-scoped action carries).</summary>
    public static string? IntegrationId(IntegrationJourneyView view) => view.MatchedIntegrations.FirstOrDefault(m => m.IntegrationId is not null)?.IntegrationId;

    public static StepAction Action(JourneySetupStep step, IntegrationJourneyView view, string? profileId)
    {
        var integration = IntegrationId(view);
        string Iqr(string viewKey) => $"/integration-quality-review?view={viewKey}{(integration is null ? "" : $"&integration={Uri.EscapeDataString(integration)}")}";
        return step.Kind switch
        {
            JourneySetupStepKind.Integration => integration is null
                ? new("Configure integration", IntegrationReviewPresentation.IntegrationsHref(profileId), "Check the existing integrations first — a matching one is reused, never duplicated.")
                : new("Review integration", IntegrationReviewPresentation.IntegrationHref(profileId, integration), null),
            JourneySetupStepKind.SourceEvidence => integration is null
                ? new("Bind source evidence", SourceGuidancePresentation.ActionHref("iqr-evidence"), null)
                : new(step.Status == JourneySetupStepStatus.Ready ? "Review source evidence" : "Bind source evidence", IntegrationTemplatePresentation.ChangeEvidenceHref(integration), null),
            JourneySetupStepKind.Contract => new("Review contract", integration is null ? SourceGuidancePresentation.ActionHref("iqr-evidence") : Iqr(IntegrationReviewPrerunPresentation.SetupView), null),
            JourneySetupStepKind.Environment => new("Review & apply safe known values", TestPackPresentation.SafeConfigurationAnchor, "Only empty fields are filled; explicit values, secrets, identities and trust are never applied."),
            JourneySetupStepKind.Authentication => new("Configure local execution", null,
                "Manual requirement: secrets (for example the ID-porten client secret) are configured in the backend's local secret store. BirkNext never imports or stores them through setup."),
            JourneySetupStepKind.Authorization => new("Record the confirmation", null,
                "Manual requirement: an authorization policy confirmation is a person's attestation in backend configuration. It is never applied or imported automatically."),
            JourneySetupStepKind.TestData => new("Open Test Data", "/test-data", "Approved synthetic test data only; identities are never generated by setup."),
            JourneySetupStepKind.ExecutionProvider => new("Review execution provider", integration is null ? "/integration-quality-review?view=test-verify" : Iqr(IntegrationReviewPrerunPresentation.TestView), null),
            JourneySetupStepKind.RuntimeVerification => new("View runtime evidence", null, "Downstream verification needs a runtime evidence provider; transport acceptance is never a pass."),
            _ => new("Manage active execution", TestPackPresentation.ExecutionSettingsHref, "Trusted execution is enabled explicitly by an administrator; setup never enables it."),
        };
    }

    /// <summary>The element id of a step (for Continue setup focus).</summary>
    public static string StepId(string journeyId, JourneySetupStepKind kind) => $"setup-{journeyId}-{kind.ToString().ToLowerInvariant()}";
}

/// <summary>Where a setup-profile panel sends its requests: the shared panel (validate → preview → apply selected → export) over any consumer's
/// profile endpoints. Every implementation keeps the same rules: preview never mutates, apply needs explicit selection, export is sanitized.</summary>
public interface ISetupProfileTransport
{
    Task<(SetupProfilePreview? Value, string? Error)> PreviewAsync(SetupProfileRequest request);
    Task<(SetupApplyResult? Value, string? Error)> ApplyAsync(SetupApplyRequest request);
    /// <summary><paramref name="example"/>: the placeholder example instead of the current safe setup.</summary>
    Task<(SetupProfileExport? Value, string? Error)> ExportAsync(bool example, SetupProfileFormat format);
}

/// <summary>Which half of the setup-profile panel is open.</summary>
public enum SetupProfileMode { Import, Export }
