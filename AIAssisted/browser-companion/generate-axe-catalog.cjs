// Reproducible mapping from the pinned, bundled axe engine. No WCAG criterion metadata is duplicated.
const fs = require('node:fs');
const path = require('node:path');
const axe = require('./vendor/axe.min.js');
const entries = axe.getRules(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).map(rule => {
  const ids = rule.tags.map(t => /^wcag(\d)(\d)(\d{1,2})$/.exec(t)).filter(Boolean).map(m => `${m[1]}.${m[2]}.${m[3]}`);
  return `        ["${rule.ruleId}"] = [${ids.map(id => `"${id}"`).join(', ')}],`;
});
const content = `// Generated by browser-companion/generate-axe-catalog.cjs from the bundled backend axe asset.
namespace BirkNext.BrowserCompanion;

public static class AxeRuleCatalog
{
    public const string Version = "${axe.version}";
    private static readonly IReadOnlyDictionary<string, string[]> Rules = new Dictionary<string, string[]>
    {
${entries.join('\n')}
    };
    public static IReadOnlyList<string> Criteria(string ruleId) => Rules.TryGetValue(ruleId, out var ids) ? ids : [];
    public static bool CanEvaluate(string criterionId) => Rules.Values.Any(ids => ids.Contains(criterionId));
}
`;
const target = path.resolve(__dirname, '../shared/AxeRuleCatalog.cs');
if (process.argv.includes('--check')) {
  // Compare content, not line endings: a Windows checkout (core.autocrlf) has CRLF while the generator writes LF.
  const lf = text => text.replace(/\r\n/g, '\n');
  if (lf(fs.readFileSync(target, 'utf8')) !== lf(content)) throw new Error('Axe catalogue does not match bundled engine; regenerate it.');
} else fs.writeFileSync(target, content);
